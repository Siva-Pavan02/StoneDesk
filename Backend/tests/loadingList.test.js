const test = require('node:test');
const assert = require('node:assert/strict');
const database = require('./database');
const app = require('../server');
const API_PREFIX = '/api';
test('loading lists retain IDs, validate JSON and persist updates', async t => {
  await database.setup(t);
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = 'http://127.0.0.1:' + server.address().port;
  const cookie = await require('./authHelper').adminCookie(base);
  async function call(method, route, body) {
    const r = await fetch(base + API_PREFIX + '/loading-lists' + route, { method, headers: { Cookie: cookie, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: r.status, data: await r.json() };
  }
  const body = { supervisor: 'Test', buyerDestination: 'Kadapa', stoneType: 'Stone', finish: 'Honed', requirements: [{ lengthFt: 3, widthFt: 2, requiredQuantity: 19 }] };
  const created = await call('POST', '', body);
  assert.equal(created.status, 201);
  const id = created.data.id;
  assert.ok(id);
  assert.equal(created.data.requirements[0].balance, 19);
  const changed = await call('PUT', '/' + id, { requirements: [{ ...created.data.requirements[0], loadedQuantity: 1, loadedPieces: [{ lengthFt: 3, widthFt: 2, sqFt: 100 }] }] });
  assert.equal(changed.status, 200);
  assert.equal(changed.data.requirements[0].loadedPieces[0].sqFt, 6);
  assert.equal(changed.data.requirements[0].balance, 18);
  assert.equal((await call('PUT', '/' + id, { requirements: [{ lengthFt: -1, widthFt: 2, requiredQuantity: 1 }] })).status, 400);
  assert.equal((await call('GET', '/' + id)).data.id, id);
  assert.equal((await call('DELETE', '/' + id)).status, 200);
  assert.equal((await call('GET', '/' + id)).status, 404);
  const org = await database.prisma.masterSettings.findFirst();
  const other = await database.prisma.masterSettings.create({ data: { organizationId: 'OTHER-LISTS' } });
  const rows = Array.from({ length: 25 }, (_, n) => ({ organizationId: org.id, loadingListNumber: `LL-${n}`, supervisor: 'Test', buyerDestination: n < 2 ? 'Old Kadapa' : 'Recent', stoneType: 'Stone', finish: 'Honed', requirements: Array.from({ length: 100 }, () => ({ lengthFt: 3, widthFt: 2, requiredQuantity: 19, loadedPieces: [] })), createdAt: new Date(2026,0,n+1) }));
  await database.prisma.loadingList.createMany({ data: [...rows, { ...rows[0], organizationId: other.id }] });
  const page = await call('GET', '');
  assert.equal(page.data.data.length,20);
  assert.ok(page.data.nextCursor);
  assert.equal(page.data.data[0].requirements,undefined);
  const next = await call('GET','?cursor='+page.data.nextCursor);
  assert.equal(next.data.data.length,5); assert.equal(next.data.nextCursor,null);
  const search = await call('GET','?q=old%20KADAPA&limit=1');
  assert.equal(search.data.data[0].loadingListNumber,'LL-1');
  const foreign = await database.prisma.loadingList.findFirst({where:{organizationId:other.id}});
  assert.equal((await call('GET','?cursor='+foreign.id)).status,400);
  for (const invalid of ['limit=0','limit=51','limit=2x','limit=1&limit=2','status=Invalid','q='+'x'.repeat(121),'cursor=nope']) assert.equal((await call('GET','?'+invalid)).status,400,invalid);
  const detail = await call('GET','/'+page.data.data[0].id);
  assert.equal(detail.data.requirements.length,100);
  const original = await database.prisma.loadingList.findMany({where:{organizationId:org.id},orderBy:{createdAt:'desc'}});
  const before = Buffer.byteLength(JSON.stringify(original)), after = Buffer.byteLength(JSON.stringify(page.data));
  console.log(`Loading-list fixture: before=${before} bytes/25 full records; after=${after} bytes/20 summaries`);
  assert.ok(after < before / 10);
});
